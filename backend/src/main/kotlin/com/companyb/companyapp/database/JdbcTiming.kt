package com.companyb.companyapp.database

import com.companyb.companyapp.logging.RequestQueryTally
import java.sql.Connection
import java.sql.PreparedStatement
import java.sql.Statement
import javax.sql.DataSource

/**
 * Times every statement that runs through a [DataSource] and reports it to
 * [RequestQueryTally]. Plain Kotlin delegation: a data source hands out timed
 * connections, a connection hands out timed statements, and a statement times
 * the calls that run SQL. Everything else passes straight through. Only
 * statement execution is counted: connection checkout, commit and rollback are
 * not. Two entry points stay untimed because the app uses neither and detekt
 * caps overloads at five: `prepareCall` and `prepareStatement(sql, int[])`.
 */
object JdbcTiming {
    fun wrap(source: DataSource): DataSource = TimedDataSource(source)
}

private inline fun <T> timed(
    sql: String,
    run: () -> T,
): T {
    val start = System.nanoTime()
    try {
        return run()
    } finally {
        RequestQueryTally.record(sql, System.nanoTime() - start)
    }
}

private const val BATCH_SQL = "(batch)"

private class TimedDataSource(
    private val source: DataSource,
) : DataSource by source {
    override fun getConnection(): Connection = TimedConnection(source.connection)

    override fun getConnection(
        username: String?,
        password: String?,
    ): Connection = TimedConnection(source.getConnection(username, password))
}

private class TimedConnection(
    private val connection: Connection,
) : Connection by connection {
    override fun createStatement(): Statement = TimedStatement(connection.createStatement())

    override fun createStatement(
        resultSetType: Int,
        resultSetConcurrency: Int,
    ): Statement = TimedStatement(connection.createStatement(resultSetType, resultSetConcurrency))

    override fun createStatement(
        resultSetType: Int,
        resultSetConcurrency: Int,
        resultSetHoldability: Int,
    ): Statement = TimedStatement(connection.createStatement(resultSetType, resultSetConcurrency, resultSetHoldability))

    override fun prepareStatement(sql: String): PreparedStatement =
        TimedPreparedStatement(connection.prepareStatement(sql), sql)

    override fun prepareStatement(
        sql: String,
        autoGeneratedKeys: Int,
    ): PreparedStatement = TimedPreparedStatement(connection.prepareStatement(sql, autoGeneratedKeys), sql)

    override fun prepareStatement(
        sql: String,
        columnNames: Array<out String>,
    ): PreparedStatement = TimedPreparedStatement(connection.prepareStatement(sql, columnNames), sql)

    override fun prepareStatement(
        sql: String,
        resultSetType: Int,
        resultSetConcurrency: Int,
    ): PreparedStatement =
        TimedPreparedStatement(connection.prepareStatement(sql, resultSetType, resultSetConcurrency), sql)

    override fun prepareStatement(
        sql: String,
        resultSetType: Int,
        resultSetConcurrency: Int,
        resultSetHoldability: Int,
    ): PreparedStatement =
        TimedPreparedStatement(
            connection.prepareStatement(sql, resultSetType, resultSetConcurrency, resultSetHoldability),
            sql,
        )
}

private class TimedStatement(
    private val statement: Statement,
) : Statement by statement {
    override fun execute(sql: String) = timed(sql) { statement.execute(sql) }

    override fun execute(
        sql: String,
        autoGeneratedKeys: Int,
    ) = timed(sql) { statement.execute(sql, autoGeneratedKeys) }

    override fun execute(
        sql: String,
        columnIndexes: IntArray,
    ) = timed(sql) { statement.execute(sql, columnIndexes) }

    override fun execute(
        sql: String,
        columnNames: Array<out String>,
    ) = timed(sql) { statement.execute(sql, columnNames) }

    override fun executeQuery(sql: String) = timed(sql) { statement.executeQuery(sql) }

    override fun executeUpdate(sql: String) = timed(sql) { statement.executeUpdate(sql) }

    override fun executeUpdate(
        sql: String,
        autoGeneratedKeys: Int,
    ) = timed(sql) { statement.executeUpdate(sql, autoGeneratedKeys) }

    override fun executeUpdate(
        sql: String,
        columnIndexes: IntArray,
    ) = timed(sql) { statement.executeUpdate(sql, columnIndexes) }

    override fun executeUpdate(
        sql: String,
        columnNames: Array<out String>,
    ) = timed(sql) { statement.executeUpdate(sql, columnNames) }

    override fun executeLargeUpdate(sql: String) = timed(sql) { statement.executeLargeUpdate(sql) }

    override fun executeBatch() = timed(BATCH_SQL) { statement.executeBatch() }

    override fun executeLargeBatch() = timed(BATCH_SQL) { statement.executeLargeBatch() }
}

private class TimedPreparedStatement(
    private val statement: PreparedStatement,
    private val sql: String,
) : PreparedStatement by statement {
    override fun execute() = timed(sql) { statement.execute() }

    override fun executeQuery() = timed(sql) { statement.executeQuery() }

    override fun executeUpdate() = timed(sql) { statement.executeUpdate() }

    override fun executeLargeUpdate() = timed(sql) { statement.executeLargeUpdate() }

    override fun executeBatch() = timed(sql) { statement.executeBatch() }

    override fun executeLargeBatch() = timed(sql) { statement.executeLargeBatch() }
}

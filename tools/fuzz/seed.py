#!/usr/bin/env python3
"""Create a few rows through the real API, then write schemathesis.generated.toml.

The fuzzer's path parameters (branchId, sessionId, ...) must point at rows that
exist, otherwise nearly every generated request ends in a 404 and never reaches
a handler. Usage: seed.py BASE_URL OUT_TOML  (owner login from TEST_USERNAME/TEST_PASSWORD;
ids are read back with psql using the PG* environment variables).
"""
import json, os, subprocess, sys, urllib.request, uuid
from datetime import date, timedelta

BASE, OUT = sys.argv[1], sys.argv[2]
BRANCH = "00000000-0000-4000-8000-000000000001"


def call(method, path, body=None, token=None):
    req = urllib.request.Request(BASE + path, method=method, data=json.dumps(body).encode() if body is not None else None)
    req.add_header("content-type", "application/json")
    if token:
        req.add_header("authorization", "Bearer " + token)
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            raw = r.read()
            return r.status, json.loads(raw) if raw else None
    except urllib.error.HTTPError as e:
        return e.code, e.read().decode()[:200]


def sql(q):
    out = subprocess.run(["psql", "-At", "-v", "ON_ERROR_STOP=1", "-c", q], capture_output=True, text=True)
    return out.stdout.strip().splitlines()[0] if out.returncode == 0 and out.stdout.strip() else None


def victim_user():
    """A user nobody logs in as: routes that revoke, deactivate or re-role {userId} must not hit a login."""
    sql(
        "insert into app_user (username, password_hash, email, display_name) "
        "values ('fuzz-victim', '$2a$10$' || repeat('x', 53), 'fuzz-victim@example.test', 'Fuzz Victim') "
        "on conflict (username) do nothing"
    )
    return sql("select id from app_user where username = 'fuzz-victim'")


_, login = call("POST", "/auth/login", {"username": os.environ["TEST_USERNAME"], "password": os.environ["TEST_PASSWORD"]})
tok = login["token"]
uid = lambda: str(uuid.uuid4())
today = date.today().isoformat()

steps = []
cat, client, prod, sess = uid(), uid(), uid(), uid()
steps.append(("category", call("POST", "/api/product-categories", {"id": cat, "name": "Fuzz oil"}, tok)))
steps.append(("product", call("POST", "/api/products", {"id": prod, "name": "Fuzz product", "productCategoryId": cat, "unitPrice": "100.00", "commissionAmount": "10.00"}, tok)))
steps.append(("inventory", call("POST", f"/api/branches/{BRANCH}/inventory", {"productId": prod}, tok)))
steps.append(("client", call("POST", "/api/clients", {"id": client, "firstName": "Fuzz", "lastName": "Client", "gender": "F", "age": 40, "earlierVisits": 0}, tok)))
steps.append(("clock-in", call("POST", "/api/attendance/clock-in", {"attendanceId": uid(), "branchId": BRANCH}, tok)))
steps.append(("session", call("POST", "/api/sessions", {"id": sess, "clientId": client, "branchId": BRANCH, "isWalkIn": True, "finalPrice": "500.00"}, tok)))
bd = sql("select id from branch_day order by date desc limit 1")
if bd:
    steps.append(("expense", call("POST", "/api/expenses", {"id": uid(), "branchDayId": bd, "amount": "50.00", "category": "PANTRY"}, tok)))
    steps.append(("remittance", call("POST", "/api/remittances", {"id": uid(), "type": "SESSION", "branchId": BRANCH, "method": "BANK_TRANSFER", "dateRangeStart": today, "dateRangeEnd": today}, tok)))
for name, (status, _) in steps:
    print(f"seed {name}: {status}", file=sys.stderr)

# path parameter name -> table holding rows to point at
TABLES = {
    "branchId": "branch", "sessionId": "session", "remittanceId": "remittance", "productId": "product",
    "clientId": "client", "inviteId": "relief_invite", "branchDayId": "branch_day",
    "requestId": "grant_relief_access", "userId": "app_user", "assignmentId": "branch_day_assignment",
    "concernId": "concern", "expenseId": "expense", "entryId": "audit_log", "bookingId": "visit_booking",
    "compensationId": "compensation", "delegateId": "medical_mission_delegate", "feedbackId": "user_feedback",
    "notificationId": "notification", "categoryId": "product_category", "breakdownId": "remittance_day_breakdown",
    "lineId": "remittance_line", "practitionerId": "app_user",
}
params, missing = {}, []
victim = victim_user()
for name, table in TABLES.items():
    v = victim if name in ("userId", "practitionerId") else sql(f"select id from {table} order by 1 limit 1")
    (params.__setitem__(name, v) if v else missing.append(name))
print("no row for: " + ", ".join(missing), file=sys.stderr)
with open(OUT, "w") as f:
    f.write("# generated by seed.py; do not edit\n[parameters]\n")
    for k, v in params.items():
        f.write(f'{k} = "{v}"\n')
